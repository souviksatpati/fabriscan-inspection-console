import { InspectionRecord } from './inspectionStore';

export interface ReportMetadata {
  station?: string;
  period?: string;
  filters?: string;
  generatedBy?: {
    fullName: string;
    userId: string;
    role: string;
  };
  generatedAt?: string;
}

export function formatKolkataDateTime(date: Date = new Date()): string {
  try {
    const parts = new Intl.DateTimeFormat('en-GB', {
      timeZone: 'Asia/Kolkata',
      day: '2-digit',
      month: '2-digit',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    }).formatToParts(date);
    const p = parts.reduce((acc, part) => ({ ...acc, [part.type]: part.value }), {} as Record<string, string>);
    return `${p.day}-${p.month}-${p.year} ${p.hour}:${p.minute}`;
  } catch {
    return date.toISOString().replace('T', ' ').substring(0, 16);
  }
}

export function getReportFilename(extension: 'xlsx' | 'pdf'): string {
  try {
    const parts = new Intl.DateTimeFormat('en-GB', {
      timeZone: 'Asia/Kolkata',
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    }).formatToParts(new Date());
    const p = parts.reduce((acc, part) => ({ ...acc, [part.type]: part.value }), {} as Record<string, string>);
    return `FabriScan_Report_${p.year}-${p.month}-${p.day}_${p.hour}${p.minute}.${extension}`;
  } catch {
    const d = new Date();
    const iso = d.toISOString().replace(/[-:]/g, '').slice(0, 15);
    return `FabriScan_Report_${iso}.${extension}`;
  }
}

interface ProcessedReportData {
  inspected: number;
  good: number;
  rejected: number;
  ftrPct: number;
  ppm: number;
  defectsByClass: Array<{ class: string; count: number; sharePct: number }>;
  records: InspectionRecord[];
  allDefects: Array<{
    serial: string;
    class: string;
    confidence: number;
    areaMm2: number;
    severity: string;
  }>;
}

function processReportData(data: InspectionRecord[]): ProcessedReportData {
  const inspected = data.length;
  const good = data.filter((r) => r.verdict === 'GOOD').length;
  const rejected = data.filter((r) => r.verdict === 'NOT_GOOD').length;
  const ftrPct = inspected > 0 ? (good / inspected) * 100 : 100;
  const ppm = inspected > 0 ? (rejected / inspected) * 1_000_000 : 0;

  const classCounts: Record<string, number> = {};
  let totalDefectsCount = 0;
  const allDefects: ProcessedReportData['allDefects'] = [];

  data.forEach((r) => {
    (r.defects || []).forEach((d) => {
      classCounts[d.class] = (classCounts[d.class] || 0) + 1;
      totalDefectsCount++;
      allDefects.push({
        serial: r.serial,
        class: d.class,
        confidence: d.confidence,
        areaMm2: d.areaMm2,
        severity: d.severity,
      });
    });
  });

  const defectsByClass = Object.entries(classCounts).map(([cls, count]) => ({
    class: cls,
    count,
    sharePct: totalDefectsCount > 0 ? (count / totalDefectsCount) * 100 : 0,
  }));

  return {
    inspected,
    good,
    rejected,
    ftrPct,
    ppm,
    defectsByClass,
    records: data,
    allDefects,
  };
}

/**
 * Export report to formatted Excel workbook (.xlsx)
 */
export async function exportExcel(data: InspectionRecord[], meta?: ReportMetadata): Promise<void> {
  const ExcelJS = await import('exceljs');
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Maruti FabriScan';
  workbook.created = new Date();

  const processed = processReportData(data);
  const genAt = meta?.generatedAt || formatKolkataDateTime();
  const station = meta?.station || 'Stamping Press Line 04 · Bay B';
  const period = meta?.period || 'Current Filter Scope';
  const filters = meta?.filters || 'Active view';
  const authorName = meta?.generatedBy?.fullName || 'Quality Inspector';
  const authorId = meta?.generatedBy?.userId || 'SYS-OP';
  const authorRole = meta?.generatedBy?.role || 'QC_INSPECTOR';

  // 1. Sheet: Summary
  const summarySheet = workbook.addWorksheet('Summary');
  summarySheet.views = [{ state: 'frozen', ySplit: 1 }];

  summarySheet.columns = [
    { header: 'Report Parameter', key: 'param', width: 32 },
    { header: 'Value', key: 'value', width: 45 },
  ];

  summarySheet.addRow({ param: 'Report Title', value: 'Maruti FabriScan - Inspection Report' });
  summarySheet.addRow({ param: 'Inspection Station', value: station });
  summarySheet.addRow({ param: 'Reporting Period', value: period });
  summarySheet.addRow({ param: 'Active Filters', value: filters });
  summarySheet.addRow({ param: 'Generated By', value: `${authorName} (${authorId}, ${authorRole})` });
  summarySheet.addRow({ param: 'Generated At (Asia/Kolkata)', value: genAt });
  summarySheet.addRow({ param: '', value: '' });
  summarySheet.addRow({ param: 'Total Inspected Units', value: processed.inspected });
  summarySheet.addRow({ param: 'Total Conforming (Good)', value: processed.good });
  summarySheet.addRow({ param: 'Total Non-Conforming (Rejected)', value: processed.rejected });
  summarySheet.addRow({ param: 'First-Time-Right (FTR %)', value: Number(processed.ftrPct.toFixed(2)) });
  summarySheet.addRow({ param: 'Defective PPM (Parts-Per-Million)', value: Math.round(processed.ppm) });

  // Style header row
  summarySheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  summarySheet.getRow(1).fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF1D4ED8' },
  };

  // 2. Sheet: Defects by class
  const classSheet = workbook.addWorksheet('Defects by class');
  classSheet.views = [{ state: 'frozen', ySplit: 1 }];
  classSheet.columns = [
    { header: 'Defect Class', key: 'class', width: 28 },
    { header: 'Occurrence Count', key: 'count', width: 20 },
    { header: 'Defect Share (%)', key: 'share', width: 20 },
  ];
  classSheet.autoFilter = 'A1:C1';

  processed.defectsByClass.forEach((item) => {
    classSheet.addRow({
      class: item.class,
      count: item.count,
      share: Number(item.sharePct.toFixed(2)),
    });
  });

  classSheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  classSheet.getRow(1).fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF1D4ED8' },
  };

  // 3. Sheet: Records
  const recordsSheet = workbook.addWorksheet('Records');
  recordsSheet.views = [{ state: 'frozen', ySplit: 1 }];
  recordsSheet.columns = [
    { header: 'Inspection Time', key: 'time', width: 22 },
    { header: 'Part Serial', key: 'serial', width: 22 },
    { header: 'Batch ID', key: 'batch', width: 18 },
    { header: 'Part Type', key: 'partType', width: 26 },
    { header: 'Scanner ID', key: 'scanner', width: 16 },
    { header: 'Station ID', key: 'station', width: 28 },
    { header: 'Verdict', key: 'verdict', width: 16 },
    { header: 'Defect Count', key: 'defectCount', width: 15 },
    { header: 'Defect Classes', key: 'defectClasses', width: 32 },
  ];
  recordsSheet.autoFilter = 'A1:I1';

  processed.records.forEach((r) => {
    const defectClasses = (r.defects || []).map((d) => d.class).join(', ') || 'None';
    const row = recordsSheet.addRow({
      time: new Date(r.scannedAt),
      serial: r.serial,
      batch: r.batchId,
      partType: r.partType,
      scanner: r.scannerId,
      station: r.stationId,
      verdict: r.verdict,
      defectCount: (r.defects || []).length,
      defectClasses,
    });
    // Real date format
    row.getCell('time').numFmt = 'dd-mm-yyyy hh:mm';
  });

  recordsSheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  recordsSheet.getRow(1).fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF1D4ED8' },
  };

  // 4. Sheet: Defect details
  const detailsSheet = workbook.addWorksheet('Defect details');
  detailsSheet.views = [{ state: 'frozen', ySplit: 1 }];
  detailsSheet.columns = [
    { header: 'Part Serial', key: 'serial', width: 22 },
    { header: 'Defect Class', key: 'class', width: 24 },
    { header: 'Confidence (%)', key: 'confidence', width: 18 },
    { header: 'Area (mm²)', key: 'area', width: 18 },
    { header: 'Severity', key: 'severity', width: 16 },
  ];
  detailsSheet.autoFilter = 'A1:E1';

  processed.allDefects.forEach((d) => {
    detailsSheet.addRow({
      serial: d.serial,
      class: d.class,
      confidence: Number((d.confidence * 100).toFixed(1)),
      area: Number(d.areaMm2.toFixed(2)),
      severity: d.severity,
    });
  });

  detailsSheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  detailsSheet.getRow(1).fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF1D4ED8' },
  };

  // Download buffer
  const buffer = await workbook.xlsx.writeBuffer();
  const blob = new Blob([buffer], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
  const filename = getReportFilename('xlsx');
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Export report to formatted A4 Landscape PDF (.pdf)
 */
export async function exportPdf(data: InspectionRecord[], meta?: ReportMetadata): Promise<void> {
  const { jsPDF } = await import('jspdf');
  const autoTableModule = await import('jspdf-autotable');
  const autoTable = (autoTableModule as any).default || autoTableModule;

  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'mm',
    format: 'a4',
  });

  const processed = processReportData(data);
  const genAt = meta?.generatedAt || formatKolkataDateTime();
  const station = meta?.station || 'Stamping Press Line 04 · Bay B';
  const period = meta?.period || 'Current Filter Scope';
  const filters = meta?.filters || 'Active view';
  const authorName = meta?.generatedBy?.fullName || 'Quality Inspector';
  const authorId = meta?.generatedBy?.userId || 'SYS-OP';
  const authorRole = meta?.generatedBy?.role || 'QC_INSPECTOR';

  // 1. Report Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text('Maruti FabriScan - Inspection Report', 14, 15);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(`Station: ${station}   |   Period: ${period}   |   Filters: ${filters}`, 14, 21);
  doc.text(
    `Generated by: ${authorName} (${authorId}, ${authorRole})   |   Generated at: ${genAt} (Asia/Kolkata)`,
    14,
    26
  );

  // 2. Summary KPI Box Table
  autoTable(doc, {
    startY: 31,
    head: [['Inspected Parts', 'Conforming (Good)', 'Rejected (Not Good)', 'FTR (%)', 'Defective PPM']],
    body: [
      [
        processed.inspected.toLocaleString(),
        processed.good.toLocaleString(),
        processed.rejected.toLocaleString(),
        `${processed.ftrPct.toFixed(2)}%`,
        Math.round(processed.ppm).toLocaleString(),
      ],
    ],
    theme: 'grid',
    headStyles: {
      fillColor: [29, 78, 216],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 9,
    },
    styles: {
      font: 'helvetica',
      fontSize: 9,
      cellPadding: 2.5,
      halign: 'center',
    },
    margin: { left: 14, right: 14 },
  });

  // 3. Defects By Class Summary Table
  const defectsByClassBody =
    processed.defectsByClass.length > 0
      ? processed.defectsByClass.map((d) => [d.class, d.count.toString(), `${d.sharePct.toFixed(1)}%`])
      : [['No anomalies recorded', '0', '0%']];

  autoTable(doc, {
    startY: (doc as any).lastAutoTable.finalY + 5,
    head: [['Defect Class', 'Anomaly Count', 'Share (%)']],
    body: defectsByClassBody,
    theme: 'grid',
    headStyles: {
      fillColor: [71, 85, 105],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
    },
    styles: {
      font: 'helvetica',
      fontSize: 8,
      cellPadding: 2,
    },
    margin: { left: 14, right: 14 },
  });

  // 4. Inspection Records Table (Repeated Headers)
  const recordsBody = processed.records.map((r) => [
    formatKolkataDateTime(new Date(r.scannedAt)),
    r.serial,
    r.batchId,
    r.partType,
    r.scannerId,
    r.stationId,
    r.verdict,
    (r.defects || []).length.toString(),
    (r.defects || []).map((d) => d.class).join(', ') || 'None',
  ]);

  autoTable(doc, {
    startY: (doc as any).lastAutoTable.finalY + 6,
    head: [
      [
        'Time',
        'Serial',
        'Batch',
        'Part Type',
        'Scanner',
        'Station',
        'Verdict',
        'Defects',
        'Classes',
      ],
    ],
    body: recordsBody.length > 0 ? recordsBody : [['No records matching criteria', '', '', '', '', '', '', '', '']],
    theme: 'striped',
    showHead: 'everyPage',
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8,
    },
    styles: {
      font: 'helvetica',
      fontSize: 7.5,
      cellPadding: 1.8,
    },
    columnStyles: {
      0: { cellWidth: 28 },
      1: { cellWidth: 26 },
      2: { cellWidth: 22 },
      3: { cellWidth: 36 },
      4: { cellWidth: 20 },
      5: { cellWidth: 40 },
      6: { cellWidth: 18, fontStyle: 'bold' },
      7: { cellWidth: 16, halign: 'center' },
    },
    didParseCell: (hookData: any) => {
      if (hookData.section === 'body' && hookData.column.index === 6) {
        if (hookData.cell.raw === 'NOT_GOOD') {
          hookData.cell.styles.textColor = [185, 28, 28];
        } else if (hookData.cell.raw === 'GOOD') {
          hookData.cell.styles.textColor = [21, 128, 61];
        }
      }
    },
    margin: { left: 14, right: 14, bottom: 15 },
  });

  // 5. Defect Details Table (if anomalies exist)
  if (processed.allDefects.length > 0) {
    autoTable(doc, {
      startY: (doc as any).lastAutoTable.finalY + 6,
      head: [['Part Serial', 'Defect Class', 'Confidence', 'Area (mm²)', 'Severity']],
      body: processed.allDefects.map((d) => [
        d.serial,
        d.class,
        `${(d.confidence * 100).toFixed(1)}%`,
        d.areaMm2.toFixed(2),
        d.severity,
      ]),
      theme: 'grid',
      showHead: 'everyPage',
      headStyles: {
        fillColor: [185, 28, 28],
        textColor: [255, 255, 255],
        fontStyle: 'bold',
        fontSize: 8,
      },
      styles: {
        font: 'helvetica',
        fontSize: 7.5,
        cellPadding: 1.8,
      },
      margin: { left: 14, right: 14, bottom: 15 },
    });
  }

  // 6. Page Numbers & Confidential Footer on All Pages: "Page x of y"
  const totalPages = (doc as any).getNumberOfPages ? (doc as any).getNumberOfPages() : (doc.internal as any).getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(148, 163, 184);
    doc.text('Maruti FabriScan AOI System · Official Quality Inspection Export · Prototype Build', 14, 203);
    doc.text(`Page ${i} of ${totalPages}`, 283, 203, { align: 'right' });
  }

  const filename = getReportFilename('pdf');
  doc.save(filename);
}
